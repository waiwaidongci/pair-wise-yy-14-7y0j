function downstreamOf(edges, id) {
  const out = /* @__PURE__ */ new Set();
  const walk = (x) => {
    for (const e of edges) {
      if (e.from === x && !out.has(e.to)) {
        out.add(e.to);
        walk(e.to);
      }
    }
  };
  walk(id);
  return [...out];
}
function priorityOf(c, downstreamCount) {
  return c.retest * 2 + downstreamCount * 5 + (c.kind === "\u67F1\u7F51" ? 3 : 0);
}

